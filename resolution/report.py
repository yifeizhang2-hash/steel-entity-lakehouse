def _quantiles(values: pd.Series) -> dict[str, float]:
    if values.empty:
        return {}
    out = {f"p{int(q * 100)}": float(values.quantile(q)) for q in QUANTILES}
    out["n"] = int(len(values))
    out["max"] = float(values.max())
    return out


def probability_histogram(
    predictions: pd.DataFrame, edges: tuple[float, ...] = (0.0, 0.01, 0.1, 0.5, 0.9, 0.99, 1.01)
) -> pd.DataFrame:
    """Bucketed counts of pairwise match probability."""
    labels = [f"[{edges[i]:g}, {edges[i + 1]:g})" for i in range(len(edges) - 1)]
    buckets = pd.cut(predictions["match_probability"], bins=list(edges), right=False, labels=labels)
    counts = buckets.value_counts().reindex(labels).fillna(0).astype(int)
    return counts.rename_axis("match_probability").reset_index(name="pairs")


def best_per_record(predictions: pd.DataFrame, side: str) -> pd.DataFrame:
    """Highest-scoring candidate for each record on one side.

    Splink emits `unique_id_l` / `unique_id_r`; which side is which is fixed by the
    order the frames were given to the Linker.
    """
    key = "unique_id_l" if side == "gspt" else "unique_id_r"
    ordered = predictions.sort_values("match_probability", ascending=False)
    return ordered.groupby(key, as_index=False).first()


# --------------------------------------------------------------------------------------
# 3. per-comparator weights
# --------------------------------------------------------------------------------------


# Below this many candidate pairs, an EM estimate is arithmetic rather than evidence.
LOW_SUPPORT_PAIRS = 10


@dataclass
class ComparatorRow:
    comparison: str
    level: str
    m: float | None
    u: float | None
    pairs: int = 0
    # Splink's null level carries no weight by design: it means "no evidence either
    # way", not "unestimated". It must not be reported as a failed estimate.
    is_null: bool = False

    @property
    def low_support(self) -> bool:
        """Estimated, but from too few pairs to be believed."""
        return self.estimated and 0 < self.pairs < LOW_SUPPORT_PAIRS

    @property
    def bayes_factor(self) -> float | None:
        if self.m is None or self.u in (None, 0):
            return None
        return self.m / self.u

    @property
    def match_weight(self) -> float | None:
        factor = self.bayes_factor
        if factor is None or factor <= 0:
            return None
        return math.log2(factor)

    @property
    def estimated(self) -> bool:
        return self.m is not None and self.u is not None


@dataclass
class ComparatorReport:
    rows: list[ComparatorRow] = field(default_factory=list)

    @property
    def unestimated(self) -> list[ComparatorRow]:
        """Levels EM could not estimate. Reported, never filled in with a guess."""
        return [r for r in self.rows if not r.estimated and not r.is_null]

    def as_frame(self) -> pd.DataFrame:
        return pd.DataFrame(
            [
                {
                    "comparison": r.comparison,
                    "level": r.level,
                    "m": r.m,
                    "u": r.u,
                    "bayes_factor": r.bayes_factor,
                    "match_weight": r.match_weight,
                }
                for r in self.rows
            ]
        )

    def render(self) -> str:
        lines = [
            "3. Comparator weights, estimated by EM",
            "-" * 68,
            f"  {'comparison':<12s} {'level':<20s} {'pairs':>6s} {'m':>9s} {'u':>9s}"
            f" {'BF':>9s} {'weight':>7s}",
        ]
        for row in self.rows:
            if row.is_null:
                lines.append(
                    f"  {row.comparison:<12s} {'(null: no evidence)':<20s} {row.pairs:>6d}"
                    f" {'--':>9s} {'--':>9s} {'--':>9s} {'0.00':>7s}"
                )
                continue
            m = f"{row.m:.6f}" if row.m is not None else "     --"
            u = f"{row.u:.6f}" if row.u is not None else "     --"
            factor = f"{row.bayes_factor:.1f}" if row.bayes_factor is not None else "--"
            weight = f"{row.match_weight:.2f}" if row.match_weight is not None else "--"
            flag = "  <-- low support" if row.low_support else ""
            lines.append(
                f"  {row.comparison:<12s} {row.level[:20]:<20s} {row.pairs:>6d}"
                f" {m:>9s} {u:>9s} {factor:>9s} {weight:>7s}{flag}"
            )
        if self.unestimated:
            lines += [
                "",
                "  NOT ESTIMABLE -- left unset rather than guessed. Every one of these is a",
                "  level that zero candidate pairs fell into, so there was nothing to learn from:",
            ]
            for row in self.unestimated:
                missing = ", ".join(
                    part for part, value in (("m", row.m), ("u", row.u)) if value is None
                )
                lines.append(
                    f"    {row.comparison}.{row.level}  ({row.pairs} pairs, missing {missing})"
                )
        low = [r for r in self.rows if r.low_support]
        if low:
            lines += [
                "",
                f"  LOW SUPPORT -- estimated from fewer than {LOW_SUPPORT_PAIRS} pairs. The number",
                "  exists but should not be relied on:",
            ]
            for row in low:
                lines.append(
                    f"    {row.comparison}.{row.level}  ({row.pairs} pairs, "
                    f"weight {row.match_weight:.2f})"
                )
        return "\n".join(lines)


def _gamma_values(levels: list[dict]) -> list[tuple[dict, int]]:
    """Pair each comparison level with the gamma value Splink will emit for it.

    The saved model JSON does not carry the value, so it is reconstructed the way
    Splink assigns it: the null level is -1, and the remaining levels count *down* from
    the most specific to the ELSE level at 0.
    """
    non_null = [level for level in levels if not level.get("is_null_level")]
    top = len(non_null) - 1
    out: list[tuple[dict, int]] = []
    index = 0
    for level in levels:
        if level.get("is_null_level"):
            out.append((level, -1))
        else:
            out.append((level, top - index))
            index += 1
    return out


def comparator_report(model: TrainedModel) -> ComparatorReport:
    """Per-level m, u, Bayes factor and weight, with the pair count each rests on.

    The pair count is not decoration. A level with a large weight and three supporting
    pairs is a different object from one with the same weight and three hundred, and the
    table is useless for judging evidence unless both are visible.
    """
    settings = model.linker.misc.save_model_to_json()
    predictions = model.predictions
    rows: list[ComparatorRow] = []
    for comparison in settings["comparisons"]:
        name = comparison["output_column_name"]
        gamma = f"gamma_{name}"
        occupancy = (
            predictions[gamma].value_counts().to_dict() if gamma in predictions.columns else {}
        )
        for level, value in _gamma_values(comparison["comparison_levels"]):
            rows.append(
                ComparatorRow(
                    comparison=name,
                    level=str(level.get("label_for_charts", "?")),
                    m=level.get("m_probability"),
                    u=level.get("u_probability"),
                    pairs=int(occupancy.get(value, 0)),
                    is_null=bool(level.get("is_null_level", False)),
                )
            )
    return ComparatorReport(rows=rows)


