"""Measure what the model does: blocking reach, calibration, and per-comparator weights.

[pandas] Nothing here imports Polars or `ingest`.

The per-comparator table is the important output. It is what says which evidence is
actually doing the work, and it is the only honest way to answer "why did this pair
score what it scored".
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd
import pyarrow as pa

from lakehouse.catalog import write_table
from lakehouse.paths import RESOLUTION_NAMESPACE
from resolution.model import TrainedModel, train

MATCH_TABLE = "gspt_plantgen_candidates"

# The two most crowded counties in PLANTGEN, and they behave completely differently.
# Allegheny (Pittsburgh) has 9 plants and 9 distinct ZIPs, so ZIP fully separates them.
# Cook (Chicago) has 10 plants but only 7 distinct ZIPs and one plant with no ZIP at
# all -- county and ZIP fail *together* there. An average over all shared-county plants
# hides that, so Cook is reported on its own.
WATCHED_COUNTIES = {"17031": "Cook IL (Chicago)", "42003": "Allegheny PA (Pittsburgh)"}

QUANTILES = (0.5, 0.75, 0.9, 0.95, 0.99, 1.0)


# --------------------------------------------------------------------------------------
# 1. blocking
# --------------------------------------------------------------------------------------


@dataclass(frozen=True)
class BlockingReport:
    left_records: int
    right_records: int
    cartesian_pairs: int
    blocked_pairs: int
    fallback_records: int
    fallback_pairs: int

    @property
    def reduction_ratio(self) -> float:
        """Share of the full cross join that blocking removed.

        `blocked_pairs` already includes the pairs generated by the fallback rule for
        records no blocking key could reach. Excluding them would flatter the ratio by
        pretending the hardest records do not exist.
        """
        return 1 - (self.blocked_pairs / self.cartesian_pairs)

    def render(self) -> str:
        return "\n".join(
            [
                "1. Blocking",
                "-" * 68,
                f"  GSPT records                                 {self.left_records:>7d}",
                f"  PLANTGEN records                             {self.right_records:>7d}",
                f"  full cross join                              {self.cartesian_pairs:>7d}",
                f"  candidate pairs after blocking               {self.blocked_pairs:>7d}",
                f"    of which from the no-key fallback          {self.fallback_pairs:>7d}"
                f"   ({self.fallback_records} records with no blocking key)",
                f"  reduction ratio (fallback included)          {self.reduction_ratio:>7.4f}",
            ]
        )


def blocking_report(model: TrainedModel) -> BlockingReport:
    left, right = model.gspt, model.plantgen
    fallback_left = int((~left["has_blocking_key"]).sum())
    fallback_right = int((~right["has_blocking_key"]).sum())
    # Every no-key record on either side is paired with the whole of the other side.
    fallback_pairs = fallback_left * len(right) + fallback_right * len(left)
    fallback_pairs -= fallback_left * fallback_right
    return BlockingReport(
        left_records=len(left),
        right_records=len(right),
        cartesian_pairs=len(left) * len(right),
        blocked_pairs=len(model.predictions),
        fallback_records=fallback_left + fallback_right,
        fallback_pairs=fallback_pairs,
    )


