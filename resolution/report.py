@dataclass
class ResolutionReport:
    blocking: BlockingReport
    comparators: ComparatorReport
    histogram: pd.DataFrame
    overall_quantiles: dict[str, float]
    by_county_crowding: pd.DataFrame
    watched_counties: pd.DataFrame
    canada: pd.DataFrame
    em_sessions: list[str]
    em_failures: list[str]

    def render(self) -> str:
        parts = [self.blocking.render(), ""]
        parts += [
            "2. Pairwise match probability",
            "-" * 68,
            self.histogram.to_string(index=False),
            "",
            "  quantiles over all candidate pairs: "
            + ", ".join(f"{k}={v:.4g}" for k, v in self.overall_quantiles.items()),
            "",
            self.comparators.render(),
            "",
            "4. Best match per PLANTGEN plant, by how crowded its county is",
            "-" * 68,
            self.by_county_crowding.to_string(index=False),
            "",
            "4b. The two most crowded counties, which do NOT behave alike",
            "-" * 68,
            "   Averaging over all shared-county plants hides this: ZIP rescues",
            "   Pittsburgh completely and does not rescue Chicago at all.",
            self.watched_counties.to_string(index=False),
            "",
            "5. Canadian GSPT plants (PLANTGEN is a US census: no counterpart exists)",
            "   Kept in the denominator on purpose. Dropping them in staging would shrink",
            "   the denominator and make the match rate look better than it is.",
            "-" * 68,
            self.canada.to_string(index=False),
        ]
        if self.em_failures:
            parts += ["", "EM passes that failed:", *[f"  {f}" for f in self.em_failures]]
        return "\n".join(parts)


def _watched_county_report(merged: pd.DataFrame, plantgen: pd.DataFrame) -> pd.DataFrame:
    """Per-county detail for the counties where blocking is weakest.

    ZIP is the evidence that is supposed to rescue a shared county. Whether it can is a
    property of the individual county, not of "shared counties" as a class, so the ZIP
    cardinality is reported next to the match outcome.
    """
    zips = plantgen.set_index("unique_id")["zip5"]
    rows = []
    for fips, label in sorted(WATCHED_COUNTIES.items()):
        members = merged[merged["county_fips"] == fips]
        member_zips = zips.reindex(members["unique_id"])
        rows.append(
            {
                "county": label,
                "plants": int(len(members)),
                "with_zip": int(member_zips.notna().sum()),
                "distinct_zips": int(member_zips.nunique(dropna=True)),
                "zip_separates_all": bool(
                    member_zips.notna().all() and member_zips.nunique(dropna=True) == len(members)
                ),
                "best_above_0_9": int((members["match_probability"] > 0.9).sum()),
                "best_above_0_5": int((members["match_probability"] > 0.5).sum()),
            }
        )
    return pd.DataFrame(rows)


def build(
    db_path: Path | None = None,
    warehouse: Path | None = None,
    model: TrainedModel | None = None,
    write: bool = True,
) -> tuple[TrainedModel, ResolutionReport]:
    """Train (or reuse) the model and produce every acceptance measurement."""
    trained = model if model is not None else train(db_path, warehouse)
    predictions = trained.predictions

    # PLANTGEN-side view: does a shared county leave the model anything to work with?
    plantgen = trained.plantgen[["unique_id", "county_fips"]].copy()
    crowding = plantgen.groupby("county_fips")["unique_id"].transform("size")
    plantgen["county_crowding"] = crowding.map(lambda n: "shared county" if n > 1 else "alone")

    best_right = best_per_record(predictions, "plantgen")[
        ["unique_id_r", "match_probability", "match_weight"]
    ].rename(columns={"unique_id_r": "unique_id"})
    merged = plantgen.merge(best_right, on="unique_id", how="left")
    merged["match_probability"] = merged["match_probability"].fillna(0.0)

    by_crowding = (
        merged.groupby("county_crowding")["match_probability"]
        .agg(
            plants="size",
            median="median",
            p75=lambda s: s.quantile(0.75),
            p90=lambda s: s.quantile(0.9),
            max="max",
            above_0_5=lambda s: int((s > 0.5).sum()),
            above_0_9=lambda s: int((s > 0.9).sum()),
        )
        .reset_index()
    )

    watched = _watched_county_report(merged, trained.plantgen)

    # Canada: 8 GSPT plants whose counterpart cannot exist. Kept in the denominator on
    # purpose -- filtering them out would shrink it and make the match rate look better
    # than it is.
    canadian_ids = sorted(trained.gspt.loc[trained.gspt["country_area"] == "Canada", "unique_id"])
    pair_counts = predictions["unique_id_l"].value_counts()
    best_left = best_per_record(predictions, "gspt").set_index("unique_id_l")
    canada = pd.DataFrame(
        [
            {
                "unique_id_l": plant,
                "candidate_pairs": int(pair_counts.get(plant, 0)),
                # "never compared" and "compared and rejected" are different outcomes and
                # must not both be printed as a probability of zero.
                "outcome": "never compared"
                if pair_counts.get(plant, 0) == 0
                else "compared, best below threshold",
                "best_match_probability": float(
                    best_left.loc[plant, "match_probability"] if plant in best_left.index else 0.0
                ),
            }
            for plant in canadian_ids
        ]
    )

    report = ResolutionReport(
        blocking=blocking_report(trained),
        comparators=comparator_report(trained),
        histogram=probability_histogram(predictions),
        overall_quantiles=_quantiles(predictions["match_probability"]),
        by_county_crowding=by_crowding,
        watched_counties=watched,
        canada=canada,
        em_sessions=trained.em_sessions,
        em_failures=trained.em_failures,
    )

    if write:
        keep = [
            c
            for c in (
                "unique_id_l",
                "unique_id_r",
                "match_probability",
                "match_weight",
                "gamma_zip5",
                "gamma_street",
                "gamma_place",
                "gamma_alias_place",
                "gamma_start_year",
                "gamma_county",
            )
            if c in predictions.columns
        ]
        write_table(
            RESOLUTION_NAMESPACE,
            MATCH_TABLE,
            pa.Table.from_pandas(predictions[keep], preserve_index=False),
            db_path=db_path,
            warehouse=warehouse,
        )
    return trained, report


def main(argv: list[str] | None = None) -> int:
    import argparse
    import logging

    parser = argparse.ArgumentParser(description="Train the linker and report on it.")
    parser.add_argument("--no-write", action="store_true", help="Skip writing the Iceberg table.")
    args = parser.parse_args(argv)
    logging.getLogger("splink").setLevel(logging.ERROR)
    _, report = build(write=not args.no_write)
    print(report.render())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
